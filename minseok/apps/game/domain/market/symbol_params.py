#    (game-strategy §3-3) 세부 업종은 12종목에 12개라 항상 1종목만 맞는다. 그래서 판정은
#    그룹으로 하고, 화면에는 세부 업종을 그대로 보여준다 — 묶는다고 서사를 잃지 않게.
# ⚠️ mu_daily는 **전 종목 합이 0**이다. 실드리프트를 그대로 쓰면 우상향 종목을 사서 방치하는
#    것이 유일한 최적 전략이 되어 게임이 성립하지 않는다(game-strategy §3-1).
