SIGMA_CLIP_MAX = 0.060   # 이상치 고변동 종목이 게임을 지배하지 않게
MU_CLIP = 0.0005


@dataclass(frozen=True)
class SymbolParams:
    """종목 하나의 가격 생성 파라미터."""

    symbol: str
    name: str
    sector: str          # 세부 업종 — 화면 표시용. API로 나간다
    sector_group: str    # 묶음 업종 — 섹터 이벤트 판정용. 그룹마다 3종목
    base_price_krw: int
    sigma_daily: float   # 일간 로그수익 표준편차 (SIGMA_CLIP 범위로 클리핑됨)
    mu_daily: float      # 일간 로그수익 드리프트 (전 종목 합이 0이 되도록 중심화됨)


