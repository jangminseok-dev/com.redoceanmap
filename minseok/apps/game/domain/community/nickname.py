"""토론방 표시 이름 — user_id에서 유도하는 결정론 가명 (game-harness §1-3).

**실명을 쓰지 않는 이유**: `users.name`은 가입 시 받은 실명이거나 소셜 프로필 이름이다.
공개 토론방에 그대로 띄우면 게임 참여가 곧 실명 공개가 된다. 그렇다고 유저가 고른
닉네임을 쓰려면 auth에 컬럼·설정 화면·중복 검사가 붙는데, 그건 이 슬라이스의 범위가 아니다.

**가명을 저장하지 않는 이유**: 같은 입력이면 같은 값이라 저장할 것이 없다 —
게임의 다른 값(주가·손님)과 같은 원칙이다(harness §1-A). 글 행에 닉네임을 박아두면
같은 사람의 옛 글과 새 글이 다른 이름을 갖게 되는 사고만 는다.

game은 auth를 import할 수 없으므로(스포크 상호 독립) 이 방식은 **신규 허브 포트도
필요로 하지 않는다** — user_id 하나로 닫힌다.
"""
from __future__ import annotations

from game.domain.rng.deterministic import u64

# 조합 수 = 32 × 32 × 900 = 921,600. 유저 수가 이보다 훨씬 적어야 충돌이 드물다.
# 완전한 유일성을 보장하지 않는다 — 보장하려면 저장·중복검사가 필요하고, 토론방
# 표시 이름에 그만한 비용을 들이지 않는다. 화면은 닉네임 옆에 글 작성자 본인 여부를
# 따로 표시하므로(`mine`) 동명이인이 신원을 흐리지 않는다.
_ADJECTIVES = (
    "느긋한", "성실한", "조용한", "부지런한", "신중한", "대담한", "꼼꼼한", "낙천적인",
    "침착한", "예리한", "우직한", "재빠른", "무던한", "치밀한", "겸손한", "당당한",
    "느슨한", "단단한", "따뜻한", "산뜻한", "묵직한", "가벼운", "굳건한", "유연한",
    "말수적은", "호기심많은", "느릿한", "든든한", "야무진", "차분한", "활기찬", "담담한",
)

_NOUNS = (
    "개미", "고래", "여우", "수달", "너구리", "다람쥐", "부엉이", "두더지",
    "고슴도치", "펭귄", "물개", "거북이", "황소", "곰", "토끼", "사슴",
    "매", "제비", "잉어", "메기", "가재", "소라", "불가사리", "해파리",
    "참새", "까치", "기러기", "오소리", "담비", "삵", "노루", "멧돼지",
)

_SUFFIX_SPAN = 900  # 100~999 — 세 자리로 고정해 이름 길이가 흔들리지 않는다


def display_name(user_id: int) -> str:
    """user_id → 토론방 표시 이름. 같은 유저면 언제·어디서 물어도 같은 값이다."""
    seed = u64("community-nickname", str(user_id))
    adjective = _ADJECTIVES[seed % len(_ADJECTIVES)]
    noun = _NOUNS[(seed // len(_ADJECTIVES)) % len(_NOUNS)]
    suffix = 100 + (seed // (len(_ADJECTIVES) * len(_NOUNS))) % _SUFFIX_SPAN
    return f"{adjective} {noun}{suffix}"
