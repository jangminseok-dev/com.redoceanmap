"""서울시 추정매출 단위 — `당월_매출_금액`은 이름과 달리 **분기 합계**다.

근거(2026-09-08 확인): 서울 열린데이터광장 OA-15572 FAQ가 이 값을 "분기당 매출 금액"이라 부른다.
수치로도 성립한다 — 수서역 분식 2개 점포에 "월" 38,448건이면 점포당 하루 640건, 분기로 보면 213건.
서울 781개 상권 분식 점포당 중앙값 2,325만원은 ÷3=775만원/월이라 통계청 업종 연매출과 맞는다.
같은 데이터셋의 유동인구는 이미 "분기 총 ÷ 91일"로 다루고 있었다 — 매출만 월로 읽은 것이 불일치였다.

DB·ORM·CSV 적재는 원본 그대로 둔다. **월 단위 이름(monthly_*)으로 내보내는 어댑터 경계에서만** 3으로
나눈다. 비율(QoQ·YoY·주중 비중·객단가)은 분자·분모를 같이 나누므로 값이 변하지 않는다.
"""

QUARTER_MONTHS = 3


def monthly_from_quarter(value: int | float | None) -> int | None:
    """분기 합계 → 월 환산(반올림 정수). None은 그대로."""
    if value is None:
        return None
    return int(round(value / QUARTER_MONTHS))
